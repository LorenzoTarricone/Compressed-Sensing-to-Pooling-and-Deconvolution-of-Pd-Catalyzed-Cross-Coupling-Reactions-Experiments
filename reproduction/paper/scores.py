"""Step 1: deconvolution scores for the five campaigns.

Runs the Spotfire data function of this repository (Spotfire/Lorenzo_M_E_deconvolution.sfd) on the pooled-plate
exports in Data/paper/pooled_plates, with the settings used for every number in the paper:
Product peaks summed per sample and time point, zero carry-forward time correction, starting-material time
weights, a condition is kept if more than 6 of its 15 pooled readings are positive, chemical prior off, tolerance
0.01 ||y||_2 x 1, 2, 5, ... 200 (first feasible solve), x >= 0, score = 7x.

Writes scores_aggregate.csv, scores_by_condition.csv, pooled_readings.csv, plates_time_collapsed.csv,
table_scores_rows.tex and run_manifest.json to the output folder.

    python scores.py
"""
import argparse
import contextlib
import hashlib
import io
import json
import os
import platform
import re
import xml.etree.ElementTree as ET

import cvxpy
import numpy as np
import pandas as pd

from common import CATALYST_LISTS, POOLED, SFD, TIE_TOLERANCE, out

COLUMNS = ['ELN_ID', 'SAMPLE_ID', 'PLATENUMBER', 'COMPOUND', 'SAMPLENUMBER', 'AREA_TOTAL_REDUCED',
           'ColumnLabel', 'PLATEROW', 'PLATECOLUMN']

# campaign: (raw file, plate, layout, carbene position, catalyst list in the code repository)
CAMPAIGNS = {
    '334': ('ELN032036-334_plate-23_Buchwald-Hartwig_raw.csv', 23, 'horizontal', 'last', 'cats_names_35_dppdtbpf.csv'),
    '424': ('ELN032036-424_plate-13_Meldrum_raw.csv', 13, 'vertical', 'last', 'cats_names_35_dppdtbpf.csv'),
    '425': ('ELN032036-425_plate-11_Barbituric_raw.csv', 11, 'vertical', 'last', 'cats_names_35_dppdtbpf.csv'),
    '810': ('ELN032036-810_plate-1_Barluenga_raw.csv', 1, 'horizontal', 'last', 'cats_names_35.csv'),
    '821': ('ELN032036-821_plate-1_Suzuki_raw.csv', 1, 'horizontal', 'first', 'cats_names_35.csv'),
}


def sha256(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def run_function(sfd, **inputs):
    """Execute the data function script with the given inputs, as Spotfire would."""
    root = ET.parse(sfd).getroot()
    namespace = {item.find('Name').text: None for item in root.findall('Input')}
    namespace.update(inputs)
    with contextlib.redirect_stdout(io.StringIO()) as log:
        exec(compile(root.find('Script').text, sfd, 'exec'), namespace)
    return namespace, log.getvalue()


def ranks_with_ties(scores):
    """Full-library rank; scores within TIE_TOLERANCE share the range of ranks they span."""
    order = sorted(scores, key=lambda k: -scores[k])
    labels, i = {}, 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and abs(scores[order[j + 1]] - scores[order[i]]) <= TIE_TOLERANCE:
            j += 1
        label = str(i + 1) if i == j else f'{i + 1}-{j + 1}'
        for k in order[i:j + 1]:
            labels[k] = label
        i = j + 1
    return labels


DISPLAY = {'Amphos': 'AmPhos', 'Jackie Phos': 'JackiePhos', 'Mordal-Phos': 'MorDalPhos', 'P(oTol)_3': 'P(oTol)$_3$',
           'P(tBu)_3': 'P($^t$Bu)$_3$', 'PCy_3': 'PCy$_3$', 'PPh_3': 'PPh$_3$', 'Triisobutyl-Phosphatrane': 'Triisobutylphosphatrane',
           'CPhos': 'cPhos', 'cataCXlum A': 'cataCXium A', 'tBuBrettPhos': '$^t$BuBrettPhos', 'tBuXPhos': '$^t$BuXPhos',
           'Me3(OMe)-tBuXPhos': 'Me$_3$(OMe)$^t$BuXPhos', 'BINAP': '\\textit{rac}-BINAP'}


def write_latex_table(agg):
    """Longtable body: score (full-library rank) for every ligand and campaign; position 28 on one row."""
    rows = []
    for name in sorted(set(agg.catalyst) - {'rac-Antphos'}, key=lambda n: re.sub(r'textit|rac|[^a-z]', '', DISPLAY.get(n, n).lower())):
        label = 'dppdtbpf / \\textit{rac}-Antphos' if name == 'dppdtbpf' else DISPLAY.get(name, name)
        cells = []
        for c in CAMPAIGNS:
            key = 'rac-Antphos' if (name == 'dppdtbpf' and CAMPAIGNS[c][4] == 'cats_names_35.csv') else name
            r = agg[(agg.campaign == c) & (agg.catalyst == key)].iloc[0]
            cells.append(f"{max(r.score, 0):.2f} ({str(r['rank']).replace('-', '--')})")
        rows.append(label + ' & ' + ' & '.join(cells) + ' \\\\')
    with open(out('table_scores_rows.tex'), 'w') as fh:
        fh.write('% generated by reproduction/paper/scores.py; paste between \\midrule and \\bottomrule of the S2.9 score table\n')
        fh.write('\n'.join(rows) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--raw', default=POOLED, help='folder with the pooled-plate exports (default: Data/paper/pooled_plates)')
    ap.add_argument('--sfd', default=SFD, help='Spotfire data function file (default: the one in this repository)')
    args = ap.parse_args()
    data_dir = CATALYST_LISTS

    aggregate, by_condition, readings, wells, manifest = [], [], [], [], {'campaigns': {}}
    for campaign, (fname, plate, layout, carbene, cats_file) in CAMPAIGNS.items():
        raw_path = os.path.join(args.raw, fname)
        data = pd.read_csv(raw_path, encoding='utf-8-sig', low_memory=False)[COLUMNS]
        cats = pd.read_csv(os.path.join(data_dir, cats_file))
        ns, log = run_function(args.sfd, data_raw=data, time_correction=True, SM_weights=True, toll_exp=6,
                               cats_names=cats, reconstruct_all=False, chemical_prior=False, plate_number=plate,
                               n_hitters_to_return=35, plate_layout=layout, carbene_placement=carbene,
                               product_aggregation='sum')
        names = ns['cats_names']
        scores = dict(zip(ns['result_final']['Hitters'], ns['result_final']['Reconstructed Yield']))
        ranks = ranks_with_ties(scores)
        for name in names:
            aggregate.append(dict(campaign=campaign, catalyst=name, score=scores[name], rank=ranks[name]))

        conditions = [ns['chem_dict'][i].strip() for i in range(ns['reshaped_plate'].shape[0])]
        eps_used = []
        for c, condition in enumerate(conditions):
            hit_names, hit_values = ns['Compressed_Sensing_CVXPY'](ns['M'], ns['reshaped_plate'][c], n_hit=35)
            cond_scores = {n: v * ns['pool_size'] for n, v in zip(hit_names, hit_values)}
            if not cond_scores:  # no feasible tolerance in the schedule
                cond_scores = {n: float('nan') for n in names}
            cond_ranks = ranks_with_ties(cond_scores)
            for name in names:
                by_condition.append(dict(campaign=campaign, condition_index=c + 1, condition=condition,
                                         catalyst=name, score=cond_scores[name], rank=cond_ranks[name]))
            for m, mixture in enumerate(ns['reshaped_plate'][c]):
                readings.append(dict(campaign=campaign, condition_index=c + 1, condition=condition,
                                     mixture=m + 1, members='; '.join(ns['overall_result'][m]), reading=mixture))

        labels = {int(s.split(':')[0]): s.split(':', 1)[1].strip() for s in data.ColumnLabel.dropna().unique()}
        for r in range(8):
            for col in range(12):
                wells.append(dict(campaign=campaign, row='ABCDEFGH'[r], column=col + 1, condition=labels.get(col + 1, ''),
                                  reading=ns['final_array'][r, col]))
        accepted = [float(v) for v in re.findall(r'Epsilon successful:\s+([\d.eE+-]+)', log)]
        manifest['campaigns'][campaign] = dict(
            raw_file=fname, raw_sha256=sha256(raw_path), plate=plate, layout=layout, carbene=carbene,
            catalyst_list=cats_file, conditions=conditions, retained_conditions=[conditions[i] for i in ns['indices_to_keep']],
            norm_y=float(np.linalg.norm(ns['y_averaged_signal'])), accepted_epsilon=accepted[0] if accepted else None,
            time_weights=[float(w) for w in ns['time_weights']])

    pd.DataFrame(aggregate).to_csv(out('scores_aggregate.csv'), index=False)
    pd.DataFrame(by_condition).to_csv(out('scores_by_condition.csv'), index=False)
    pd.DataFrame(readings).to_csv(out('pooled_readings.csv'), index=False)
    pd.DataFrame(wells).to_csv(out('plates_time_collapsed.csv'), index=False)
    write_latex_table(pd.DataFrame(aggregate))
    manifest.update(sfd=os.path.basename(args.sfd), sfd_sha256=sha256(args.sfd), settings=dict(
        product_aggregation='sum', time_correction=True, SM_weights=True, toll_exp=6, chemical_prior=False,
        tolerance='0.01*||y||_2 x 1, 2, 5, 10, 20, 50, 100, 200 (first optimal)', score='7x', tie_tolerance=TIE_TOLERANCE),
        python=platform.python_version(), numpy=np.__version__, pandas=pd.__version__, cvxpy=cvxpy.__version__)
    json.dump(manifest, open(out('run_manifest.json'), 'w'), indent=2)
    print('scores written for', ', '.join(CAMPAIGNS))


if __name__ == '__main__':
    main()
